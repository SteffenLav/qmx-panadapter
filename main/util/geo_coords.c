#define PREFIX_COORDS_LEN (sizeof(PREFIX_COORDS) / sizeof(PREFIX_COORDS[0]))

// Shared by geo_coords_for_call() and geo_coords_iso_for_call() - both need
// the same longest-prefix-match lookup, just reading different fields of the
// winning row.
static int find_best_match(const char *call)
{
    char prefix[16];
    const char *slash = strchr(call, '/');
    size_t len = slash ? (size_t)(slash - call) : strlen(call);
    if (len >= sizeof(prefix)) {
        len = sizeof(prefix) - 1;
    }
    memcpy(prefix, call, len);
    prefix[len] = '\0';

    int best = -1;
    size_t best_len = 0;
    for (size_t i = 0; i < PREFIX_COORDS_LEN; i++) {
        size_t plen = strlen(PREFIX_COORDS[i].prefix);
        if (plen > best_len && starts_with(prefix, PREFIX_COORDS[i].prefix)) {
            best = (int)i;
            best_len = plen;
        }
    }
    return best;
}

bool geo_coords_for_call(const char *call, float *lat_out, float *lon_out)
{
    int best = find_best_match(call);
    if (best < 0) {
        return false;
    }
    *lat_out = PREFIX_COORDS[best].lat;
    *lon_out = PREFIX_COORDS[best].lon;
    return true;
}

const char *geo_coords_iso_for_call(const char *call)
{
    int best = find_best_match(call);
    if (best < 0) {
        return NULL;
    }
    return PREFIX_COORDS[best].iso3;
}
