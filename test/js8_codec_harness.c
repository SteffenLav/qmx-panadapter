/* Host test for the JS8 Normal codec core (J1 of docs/js8-feasibility.md):
 * the (174,87) LDPC tables, the colorder permutation, CRC-12, and the
 * payload bit layout.
 *
 * Build (from the repo root):
 *   gcc -O2 -Wall -I components/ft8_lib -I components/ft8_lib/ft8 \
 *       -o js8_codec_harness test/js8_codec_harness.c \
 *       components/ft8_lib/ft8/js8_codec.c components/ft8_lib/ft8/js8_tables.c \
 *       components/ft8_lib/ft8/ldpc.c components/ft8_lib/ft8/constants.c \
 *       -lm && ./js8_codec_harness
 *
 * WHY. The feasibility note ranks LDPC table transcription as risk #1, for a
 * specific reason: a wrong parity table is indistinguishable from a wrong
 * Costas array or a wrong bit order, because all three produce exactly one
 * symptom - nothing ever decodes. On the air that costs a session to find.
 * Here it costs a second.
 *
 * The tables are machine-generated by tools/gen_js8_ldpc_tables.py from
 * JS8Call 2.3.1 (tag v2.3.1, fd721e8b67ee), so nobody retypes them. This
 * harness then checks five independent things:
 *
 *  1. CRC ENGINE against a catalogued CRC. js8_crc12_raw() with polynomial
 *     0x80F over "123456789" plus 12 zero bits must give 0xF5B, the published
 *     check value of CRC-12/DECT. JS8's own polynomial (0xC06) is not in any
 *     CRC catalogue, so this proves the division loop is a correct CRC before
 *     the JS8 polynomial is trusted on top of it.
 *
 *  2. ENCODER against JS8Call's own Fortran. kRefCw[] was produced by
 *     compiling lib/ft8/encode174.f90 + lib/ft8/ldpc_174_87_params.f90
 *     unmodified with gfortran and feeding them the messages in kRefMsg[]
 *     (deterministic LCG driver). This is the arbiter for the generator
 *     matrix AND the colorder permutation together.
 *
 *  3. GENERATOR against PARITY MATRIX. The generator comes from
 *     ldpc_174_87_params.f90; Nm/Mn come from bpdecode174.f90 - two separate
 *     files. Every encoded codeword must satisfy all 87 checks. If either
 *     table were misparsed, this fails. It is a cross-check, not a
 *     comparison of the code against itself.
 *
 *  4. ROUND TRIP through bp_decode_code(), the engine FT8 uses, with the JS8
 *     code passed in - clean, then with bit errors injected - and the payload
 *     recovered through the inverse colorder with its CRC-12 verified.
 *
 *  5. PAYLOAD LAYOUT: frame(72) + itype(3) + crc(12), in that order. The
 *     feasibility note had itype FIRST; genjs8.f90 puts it after the frame.
 *
 * WHAT THIS DOES NOT PROVE. The CRC-12 POLYNOMIAL, the XOR-42 and the 13-bit
 * zero tail are transcribed from lib/crc12.cpp and genjs8.f90 and are only
 * checked here for self-consistency - pack, then check. Boost is not on this
 * machine, so augmented_crc was reimplemented rather than linked. Only a real
 * JS8Call station decoding our frame settles it. Do NOT settle it with a
 * second Tab5: two copies of this implementation share their mistakes.
 */
