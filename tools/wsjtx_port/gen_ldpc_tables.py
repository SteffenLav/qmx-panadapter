"""Turn WS 3.2.1's LDPC include files into a C header, unchanged.

Input : lib/ft8/ldpc_174_91_c_parity.f90 (Mn, Nm, nrw) and
        lib/ft8/ldpc_174_91_c_generator.f90 (g, 83 hex rows of 91 bits).
Output: main/ft8_wsjtx_tables.h. Indices stay 1-based, as in the Fortran,
so the port can index them exactly as the source does.

Usage: python tools/wsjtx_port/gen_ldpc_tables.py <ws/lib/ft8 dir>
"""
import os, re, sys

src = sys.argv[1]
par = open(os.path.join(src, "ldpc_174_91_c_parity.f90")).read()
gen = open(os.path.join(src, "ldpc_174_91_c_generator.f90")).read()


def block(name):
    m = re.search(r"data\s+%s\s*/(.*?)/" % name, par, re.S)
    return [int(v) for v in re.findall(r"-?\d+", m.group(1))]


Mn, Nm, nrw = block("Mn"), block("Nm"), block("nrw")
g = re.findall(r'"([0-9a-fA-F]{23})"', gen)
assert len(Mn) == 3 * 174 and len(Nm) == 7 * 83 and len(nrw) == 83 and len(g) == 83, \
    (len(Mn), len(Nm), len(nrw), len(g))

out = ["/* GENERATED by tools/wsjtx_port/gen_ldpc_tables.py from WS 3.2.1",
       " * lib/ft8/ldpc_174_91_c_parity.f90 and ldpc_174_91_c_generator.f90.",
       " * (c) K1JT et al., GPL-3. Do not edit: regenerate.",
       " * Fortran Mn(3,174) is stored as WSX_MN[bit-1][0..2], Nm(7,83) as",
       " * WSX_NM[check-1][0..6]; values are the Fortran 1-based indices. */",
       "#pragma once", ""]
out.append("static const short WSX_MN[174][3] = {")
out += ["  {%d,%d,%d}," % tuple(Mn[3 * i:3 * i + 3]) for i in range(174)]
out.append("};")
out.append("static const short WSX_NM[83][7] = {")
out += ["  {%s}," % ",".join(str(v) for v in Nm[7 * i:7 * i + 7]) for i in range(83)]
out.append("};")
out.append("static const unsigned char WSX_NRW[83] = {%s};" % ",".join(map(str, nrw)))
out.append("static const char WSX_G[83][24] = {")
out += ['  "%s",' % s for s in g]
out.append("};")
open("main/ft8_wsjtx_tables.h", "w", newline="\n").write("\n".join(out) + "\n")
print("ok", len(Mn) // 3, len(Nm) // 7)
